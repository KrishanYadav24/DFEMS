SET DEFINE OFF;
SET ECHO ON;

-- ----------------------------------------------------------------------------
-- 1. TABLE: APP_USER
-- Core user entity representing law enforcement & lab personnel.
-- Extended from DA2 to support Authentication (Master Req 4) and RBAC (Req 5).
-- ----------------------------------------------------------------------------
CREATE TABLE APP_USER (
    User_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    First_Name     VARCHAR2(50 CHAR) NOT NULL,
    Last_Name      VARCHAR2(50 CHAR) NOT NULL,
    Phone_Number   VARCHAR2(15 CHAR),
    Username       VARCHAR2(50 CHAR),
    Password_Hash  VARCHAR2(255 CHAR),
    Role           VARCHAR2(30 CHAR) DEFAULT 'Investigator' NOT NULL,
    Account_Status VARCHAR2(20 CHAR) DEFAULT 'Active' NOT NULL,
    Created_At     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_app_user PRIMARY KEY (User_ID),
    CONSTRAINT uq_app_user_phone UNIQUE (Phone_Number),
    CONSTRAINT uq_app_user_username UNIQUE (Username),
    CONSTRAINT chk_user_role CHECK (Role IN (
        'Admin', 
        'Investigator', 
        'Forensic Examiner', 
        'Evidence Custodian', 
        'Legal Reviewer', 
        'Auditor'
    )),
    CONSTRAINT chk_user_status CHECK (Account_Status IN ('Active', 'Suspended', 'Inactive'))
);

-- ----------------------------------------------------------------------------
-- 2. TABLE: LABORATORY
-- Forensic laboratories handling digital examinations (DA2 Table 2).
-- ----------------------------------------------------------------------------
CREATE TABLE LABORATORY (
    Laboratory_ID  NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    Lab_Name       VARCHAR2(100 CHAR) NOT NULL,
    CONSTRAINT pk_laboratory PRIMARY KEY (Laboratory_ID),
    CONSTRAINT uq_laboratory_name UNIQUE (Lab_Name)
);

-- ----------------------------------------------------------------------------
-- 3. TABLE: INVESTIGATOR
-- User subtype representing sworn case investigators (DA2 Table 3).
-- ----------------------------------------------------------------------------
CREATE TABLE INVESTIGATOR (
    User_ID        NUMBER NOT NULL,
    Badge_Number   VARCHAR2(20 CHAR) NOT NULL,
    CONSTRAINT pk_investigator PRIMARY KEY (User_ID),
    CONSTRAINT uq_investigator_badge UNIQUE (Badge_Number),
    CONSTRAINT fk_investigator_user FOREIGN KEY (User_ID) 
        REFERENCES APP_USER(User_ID) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 4. TABLE: FORENSIC_ANALYST
-- User subtype representing certified forensic examiners (DA2 Table 4).
-- ----------------------------------------------------------------------------
CREATE TABLE FORENSIC_ANALYST (
    User_ID        NUMBER NOT NULL,
    Certification  VARCHAR2(50 CHAR),
    Laboratory_ID  NUMBER NOT NULL,
    CONSTRAINT pk_forensic_analyst PRIMARY KEY (User_ID),
    CONSTRAINT fk_analyst_user FOREIGN KEY (User_ID) 
        REFERENCES APP_USER(User_ID) ON DELETE CASCADE,
    CONSTRAINT fk_analyst_lab FOREIGN KEY (Laboratory_ID) 
        REFERENCES LABORATORY(Laboratory_ID)
);

-- ----------------------------------------------------------------------------
-- 5. TABLE: LOCATION
-- Incident, seizure, and jurisdictional locations (DA2 Table 5).
-- ----------------------------------------------------------------------------
CREATE TABLE LOCATION (
    Location_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    Address        VARCHAR2(150 CHAR) NOT NULL,
    CONSTRAINT pk_location PRIMARY KEY (Location_ID)
);

-- ----------------------------------------------------------------------------
-- 6. TABLE: CASE_TABLE
-- Investigative case records with assigned lead investigator (DA2 Table 6).
-- ----------------------------------------------------------------------------
CREATE TABLE CASE_TABLE (
    Case_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    Title          VARCHAR2(100 CHAR) NOT NULL,
    Status         VARCHAR2(20 CHAR) DEFAULT 'Open' NOT NULL,
    Created_By     NUMBER NOT NULL,
    Assigned_To    NUMBER,
    Location_ID    NUMBER,
    Crime_Type     VARCHAR2(100 CHAR),
    Date_Opened    DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_case_table PRIMARY KEY (Case_ID),
    CONSTRAINT chk_case_status CHECK (Status IN (
        'Open', 
        'Under Investigation', 
        'Closed', 
        'Archived'
    )),
    CONSTRAINT fk_case_creator FOREIGN KEY (Created_By) 
        REFERENCES APP_USER(User_ID),
    CONSTRAINT fk_case_investigator FOREIGN KEY (Assigned_To) 
        REFERENCES INVESTIGATOR(User_ID),
    CONSTRAINT fk_case_location FOREIGN KEY (Location_ID) 
        REFERENCES LOCATION(Location_ID)
);

-- ----------------------------------------------------------------------------
-- 7. TABLE: ASSIGNED
-- Junction table supporting multi-investigator case assignment (DA2 Table 7).
-- ----------------------------------------------------------------------------
CREATE TABLE ASSIGNED (
    User_ID        NUMBER NOT NULL,
    Case_ID        NUMBER NOT NULL,
    Assigned_Date  DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_assigned PRIMARY KEY (User_ID, Case_ID),
    CONSTRAINT fk_assigned_investigator FOREIGN KEY (User_ID) 
        REFERENCES INVESTIGATOR(User_ID) ON DELETE CASCADE,
    CONSTRAINT fk_assigned_case FOREIGN KEY (Case_ID) 
        REFERENCES CASE_TABLE(Case_ID) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 8. TABLE: EVIDENCE
-- Master digital evidence inventory (DA2 Table 8).
-- ----------------------------------------------------------------------------
CREATE TABLE EVIDENCE (
    Evidence_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    Description      VARCHAR2(255 CHAR) NOT NULL,
    Collection_Date  DATE DEFAULT SYSDATE NOT NULL,
    Case_ID          NUMBER NOT NULL,
    Status           VARCHAR2(30 CHAR) DEFAULT 'Collected' NOT NULL,
    Hash_Value       VARCHAR2(64 CHAR),
    CONSTRAINT pk_evidence PRIMARY KEY (Evidence_ID),
    CONSTRAINT chk_evidence_status CHECK (Status IN (
        'Collected', 
        'In Storage', 
        'Under Analysis', 
        'Presented in Court', 
        'Archived', 
        'Disposed'
    )),
    CONSTRAINT fk_evidence_case FOREIGN KEY (Case_ID) 
        REFERENCES CASE_TABLE(Case_ID) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 9. TABLE: DEVICE
-- Physical seized hardware subtype (laptops, phones, drives) (DA2 Table 9).
-- ----------------------------------------------------------------------------
CREATE TABLE DEVICE (
    Device_ID      NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    Serial_Number  VARCHAR2(50 CHAR) NOT NULL,
    Evidence_ID    NUMBER NOT NULL,
    CONSTRAINT pk_device PRIMARY KEY (Device_ID),
    CONSTRAINT uq_device_serial UNIQUE (Serial_Number),
    CONSTRAINT uq_device_evidence UNIQUE (Evidence_ID),
    CONSTRAINT fk_device_evidence FOREIGN KEY (Evidence_ID) 
        REFERENCES EVIDENCE(Evidence_ID) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 10. TABLE: FILE_RECORD
-- Digital logical evidence files, memory dumps, forensic disk images (DA2 Table 10).
-- Extended with storage metadata for physical file upload/download (Master Req 10).
-- ----------------------------------------------------------------------------
CREATE TABLE FILE_RECORD (
    File_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    Evidence_ID    NUMBER NOT NULL,
    File_Name      VARCHAR2(255 CHAR),
    File_Path      VARCHAR2(500 CHAR),
    File_Size      NUMBER,
    Mime_Type      VARCHAR2(100 CHAR),
    CONSTRAINT pk_file_record PRIMARY KEY (File_ID),
    CONSTRAINT uq_file_evidence UNIQUE (Evidence_ID),
    CONSTRAINT fk_file_evidence FOREIGN KEY (Evidence_ID) 
        REFERENCES EVIDENCE(Evidence_ID) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 11. TABLE: CHAIN_OF_CUSTODY
-- Immutable append-only audit trail of evidence access & transfers (DA2 Table 11).
-- ----------------------------------------------------------------------------
CREATE TABLE CHAIN_OF_CUSTODY (
    Custody_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    Timestamp_At   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    Action         VARCHAR2(255 CHAR) NOT NULL,
    Evidence_ID    NUMBER NOT NULL,
    User_ID        NUMBER,
    CONSTRAINT pk_chain_of_custody PRIMARY KEY (Custody_ID),
    CONSTRAINT fk_custody_evidence FOREIGN KEY (Evidence_ID) 
        REFERENCES EVIDENCE(Evidence_ID) ON DELETE CASCADE,
    CONSTRAINT fk_custody_user FOREIGN KEY (User_ID) 
        REFERENCES APP_USER(User_ID) ON DELETE SET NULL
);

-- ----------------------------------------------------------------------------
-- 12. TABLE: FORENSIC_ANALYSIS
-- Analytical findings, laboratory notes, and examiner attribution (DA2 Table 12).
-- ----------------------------------------------------------------------------
CREATE TABLE FORENSIC_ANALYSIS (
    Analysis_ID    NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    Findings       VARCHAR2(500 CHAR) NOT NULL,
    Evidence_ID    NUMBER NOT NULL,
    Analyst_ID     NUMBER NOT NULL,
    Timestamp_At   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_forensic_analysis PRIMARY KEY (Analysis_ID),
    CONSTRAINT fk_analysis_evidence FOREIGN KEY (Evidence_ID) 
        REFERENCES EVIDENCE(Evidence_ID) ON DELETE CASCADE,
    CONSTRAINT fk_analysis_analyst FOREIGN KEY (Analyst_ID) 
        REFERENCES FORENSIC_ANALYST(User_ID)
);

-- ----------------------------------------------------------------------------
-- 13. TABLE: AUDIT_LOG
-- System security, login attempts, sensitive data read telemetry (Master Req 16).
-- Separated from CHAIN_OF_CUSTODY to maintain pure evidence chain of custody.
-- ----------------------------------------------------------------------------
CREATE TABLE AUDIT_LOG (
    Log_ID         NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1),
    User_ID        NUMBER,
    Action         VARCHAR2(100 CHAR) NOT NULL,
    Entity_Name    VARCHAR2(50 CHAR),
    Entity_ID      NUMBER,
    IP_Address     VARCHAR2(50 CHAR),
    Timestamp_At   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    Details        VARCHAR2(1000 CHAR),
    CONSTRAINT pk_audit_log PRIMARY KEY (Log_ID),
    CONSTRAINT fk_audit_user FOREIGN KEY (User_ID) 
        REFERENCES APP_USER(User_ID) ON DELETE SET NULL
);

-- ============================================================================
-- PERFORMANCE & INTEGRITY INDEXES
-- ============================================================================
CREATE INDEX idx_case_status ON CASE_TABLE(Status);
CREATE INDEX idx_case_assigned ON CASE_TABLE(Assigned_To);
CREATE INDEX idx_case_location ON CASE_TABLE(Location_ID);
CREATE INDEX idx_evidence_case ON EVIDENCE(Case_ID);
CREATE INDEX idx_evidence_status ON EVIDENCE(Status);
CREATE INDEX idx_evidence_hash ON EVIDENCE(Hash_Value);
CREATE INDEX idx_custody_evidence ON CHAIN_OF_CUSTODY(Evidence_ID);
CREATE INDEX idx_custody_time ON CHAIN_OF_CUSTODY(Timestamp_At);
CREATE INDEX idx_analysis_evidence ON FORENSIC_ANALYSIS(Evidence_ID);
CREATE INDEX idx_analysis_analyst ON FORENSIC_ANALYSIS(Analyst_ID);
CREATE INDEX idx_audit_user ON AUDIT_LOG(User_ID);
CREATE INDEX idx_audit_time ON AUDIT_LOG(Timestamp_At);

